// The profile reference, GENERATED from the validator.
//
// Section 11.6 requires configuration documentation to be generated from
// `FIELDS` so the two cannot drift. Hand-written documentation for a validator
// is a second inventory of it, and the copy that goes wrong is the one a reader
// trusts, with nothing reporting the disagreement.
//
// The prose is the comment ALREADY sitting above or beside each key in
// `src/profile/schema.mjs`. Passing descriptions in here instead would put them
// in a THIRD place to edit, and the third copy is the one that rots.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { FIELDS } from "../src/profile/schema.mjs";

const SCHEMA = new URL("../src/profile/schema.mjs", import.meta.url);
const OUT    = new URL("../docs/profile-reference.md", import.meta.url);

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * The line range of the `FIELDS` object literal, as [firstBodyLine, lastBodyLine].
 *
 * WHY THIS IS BOUNDED RATHER THAN SEARCHED WHOLE-FILE. Key strings are not
 * unique in this source: `"builder.capabilities.observe"` appears both in
 * `FIELDS` and again in `UNIVERSAL_DEFAULTS`, which seeds the same names with
 * their default values. A whole-file "first match" search happens to land on the
 * right one only because `FIELDS` is declared earlier in the file today. Reorder
 * the two declarations and every duplicated key would silently take its prose
 * from the wrong block -- and nothing would go red, because the committed file
 * and a fresh generation would both be wrong in the same way.
 *
 * That is the failure this module is supposed to prevent, so it must not be the
 * failure this module contains. The bound makes the lookup mean "the key's
 * declaration IN FIELDS" rather than "the first place this string appears".
 */
export function fieldsBounds(lines) {
  const start = lines.findIndex((l) => /^export const FIELDS\s*=\s*\{/.test(l));
  if (start < 0) throw new Error("profile-reference: cannot find `export const FIELDS = {`");
  const end = lines.findIndex((l, i) => i > start && /^\};/.test(l));
  if (end < 0) throw new Error("profile-reference: `FIELDS` has no closing `};`");
  return [start + 1, end - 1];
}

/**
 * The description for one key: the `//` block immediately above its declaration,
 * else the trailing `//` comment on the declaration line itself.
 *
 * BOTH FORMS ARE READ because both are in use. Of the keys declared today, 16
 * carry a block above and 13 are documented with a trailing comment. Reading
 * only the block -- which is what this generator first did -- rendered those 13
 * as empty cells while every assertion stayed green, because the committed file
 * was generated by the same blind reader.
 *
 * A block above wins when a key has both: it is the fuller prose, and the
 * trailing note beside it is usually a restatement.
 *
 * Returns "" for a key with neither. That is honest -- there is nothing to say
 * about it yet -- and the coverage count in the generated header makes the
 * silence visible rather than letting it read as a complete document.
 */
export function noteFor(source, key) {
  const lines = source.split("\n");
  const [lo, hi] = fieldsBounds(lines);
  const re = new RegExp(`^\\s*"?${escapeRe(key)}"?\\s*:`);
  let at = -1;
  for (let i = lo; i <= hi; i++) if (re.test(lines[i])) { at = i; break; }
  if (at < 0) return null;   // null means NOT FOUND, distinct from "" (found, undocumented)

  // Upwards until the first line that is not a `//` comment. A shared block above
  // a run of related keys documents only the FIRST of them and the rest fall
  // through to their trailing note, which is truer than attributing one key's
  // prose to another.
  const above = [];
  for (let i = at - 1; i >= lo; i--) {
    const m = lines[i].match(/^\s*\/\/ ?(.*)$/);
    if (!m) break;
    above.unshift(m[1]);
  }
  if (above.join(" ").trim()) return above.join(" ").trim();

  // Trailing comment, taken from AFTER the value so a `//` inside the validator
  // arguments cannot be mistaken for prose.
  const tail = lines[at].match(/\],?\s*\/\/ ?(.*)$/);
  return tail ? tail[1].trim() : "";
}

/** Every key, with its description; `note` is "" when undocumented. */
export function rowsFor(source) {
  return Object.entries(FIELDS).map(([key, [required]]) => {
    const note = noteFor(source, key);
    if (note === null)
      throw new Error(`profile-reference: \`${key}\` is declared in FIELDS but its ` +
        `declaration was not found inside the FIELDS block in schema.mjs`);
    return { key, required: Boolean(required), note };
  });
}

export function profileReference(source = readFileSync(SCHEMA, "utf8")) {
  const rows = rowsFor(source);
  const documented = rows.filter((r) => r.note !== "");

  // TWO PARTS, AND THE SPLIT IS MEASURED RATHER THAN PREFERRED. The prose in
  // this schema is rationale -- WHY a key is shaped the way it is -- and it runs
  // long: of the keys carrying a description, the median is 138 characters and
  // 13 exceed 200. Rendering that into a third table column produces cells no
  // one can read and a table no one can scan, which is a reference that is
  // technically complete and practically useless.
  //
  // So: an INDEX that stays scannable across every key, and a DETAIL section per
  // documented key where a paragraph can be a paragraph. Nothing is truncated --
  // a generator that silently drops half a sentence is a document that lies by
  // omission, and the reader cannot tell.
  const index = [
    "| key | required | documented |",
    "|---|---|---|",
    ...rows.map((r) =>
      `| \`${r.key}\` | ${r.required ? "required" : "optional"} | ${r.note ? "yes" : "—"} |`),
  ];

  const detail = documented.flatMap((r) => [
    `### \`${r.key}\``,
    "",
    `${r.required ? "**required**" : "**optional**"}`,
    "",
    r.note,
    "",
  ]);

  return [
    "# Profile reference",
    "",
    "GENERATED from `src/profile/schema.mjs`. Do not edit by hand: run",
    "`node scripts/profile-reference.mjs`, which rewrites this file. A test in",
    "`test/profile-validate.test.mjs` fails while it is stale, and",
    "`node scripts/profile-reference.mjs --check` reports staleness without writing.",
    "",
    `${rows.length} keys. ${documented.length} carry a description.`,
    "",
    "A key with no description has no comment above or beside it in",
    "`src/profile/schema.mjs` yet. Write one there and regenerate; there is nowhere",
    "else to put it, which is the point.",
    "",
    "## Index",
    "",
    ...index,
    "",
    "## Keys",
    "",
    "Only keys carrying a description appear below; the index above is complete.",
    "",
    ...detail,
  ].join("\n");
}

// Only when RUN, never when imported: the test imports this module, and a
// write-on-import would make the assertion regenerate the file it is checking --
// an instrument that repairs what it is measuring always reports success.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fresh = profileReference();
  // `--check` is the shape every generator in this class settles on (gofmt -l,
  // terraform-docs --check, prettier --check): report staleness, change nothing,
  // exit non-zero. It gives a pre-commit hook and a human the same answer the
  // suite gives, without running the suite.
  if (process.argv.includes("--check")) {
    let onDisk = null;
    try { onDisk = readFileSync(OUT, "utf8"); } catch { onDisk = null; }
    if (onDisk === fresh) { console.log("docs/profile-reference.md is current"); process.exit(0); }
    console.error(onDisk === null
      ? "docs/profile-reference.md is MISSING; run: node scripts/profile-reference.mjs"
      : "docs/profile-reference.md is STALE; run: node scripts/profile-reference.mjs");
    process.exit(1);
  }
  writeFileSync(OUT, fresh);
  console.log(`wrote docs/profile-reference.md`);
}
